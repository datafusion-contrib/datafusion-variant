//! Generate the SQL reference from the documentation attached to registered UDFs.

use std::{collections::BTreeMap, fmt::Write, path::Path};

use anyhow::{Result, ensure};
use datafusion::{execution::SessionStateBuilder, prelude::SessionContext};
use datafusion_doc::Documentation;
use datafusion_variant::register_all;

fn function_docs() -> Result<BTreeMap<String, Documentation>> {
    // An empty registry discovers only our functions, including replacements for
    // built-ins such as to_json, without maintaining a second function list.
    let mut ctx = SessionContext::new_with_state(SessionStateBuilder::new().build());
    register_all(&mut ctx)?;
    let state = ctx.state();
    let scalar = state
        .scalar_functions()
        .values()
        .map(|f| (f.name(), f.documentation()));
    let aggregate = state
        .aggregate_functions()
        .values()
        .map(|f| (f.name(), f.documentation()));
    // Documentation is opt-in while legacy helpers await settled Spark contracts.
    Ok(scalar
        .chain(aggregate)
        .filter_map(|(name, doc)| {
            doc.filter(|doc| doc.doc_section.include)
                .map(|doc| (name.to_owned(), doc.clone()))
        })
        .collect())
}

fn render(docs: &BTreeMap<String, Documentation>) -> Result<String> {
    let mut out = String::from(
        "<!-- Generated by cargo run --example generate_function_docs. Do not edit directly. -->\n\n\
         # SQL function reference\n\n\
         Documented scalar and aggregate functions registered by `register_all`.\n\
         See the [README](../README.md) for setup and common workflows.\n\n",
    );
    for name in docs.keys() {
        writeln!(out, "- [{name}](#{name})")?;
    }
    for (name, doc) in docs {
        writeln!(out, "\n## `{name}`\n\n{}\n", doc.description.trim())?;
        writeln!(out, "```sql\n{}\n```", doc.syntax_example)?;
        if let Some(alternatives) = &doc.alternative_syntax {
            writeln!(out, "\nAlternative syntax:\n\n```sql")?;
            for syntax in alternatives {
                writeln!(out, "{syntax}")?;
            }
            writeln!(out, "```")?;
        }
        if let Some(arguments) = &doc.arguments {
            writeln!(out, "\n### Arguments\n")?;
            for (name, description) in arguments {
                writeln!(out, "- **{name}**: {description}")?;
            }
        }
        if let Some(example) = &doc.sql_example {
            writeln!(out, "\n### Example\n\n{}", example.trim())?;
        }
        if let Some(related) = &doc.related_udfs {
            writeln!(out, "\n### Related functions\n")?;
            for name in related {
                ensure!(docs.contains_key(name), "unknown related function: {name}");
                writeln!(out, "- [{name}](#{name})")?;
            }
        }
    }
    Ok(out)
}

fn main() -> Result<()> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    ensure!(
        args.is_empty() || args == ["--check"],
        "Usage: cargo run --example generate_function_docs -- [--check]"
    );
    let markdown = render(&function_docs()?)?;
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("docs/sql-reference.md");
    if args.is_empty() {
        std::fs::write(path, markdown)?;
    } else {
        ensure!(
            std::fs::read_to_string(path)? == markdown,
            "SQL reference is stale; run cargo run --example generate_function_docs"
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use anyhow::Context;

    /// Check the SQL and displayed results in the same metadata we publish.
    #[tokio::test]
    async fn function_examples() -> Result<()> {
        let docs = function_docs()?;
        ensure!(!docs.is_empty(), "no documented functions found");
        for (name, doc) in docs {
            let mut ctx = SessionContext::new();
            register_all(&mut ctx)?;
            let example = doc
                .sql_example
                .with_context(|| format!("{name}: no example"))?;
            let mut lines = example.lines().peekable();
            let mut checked = 0;
            while let Some(line) = lines.next() {
                let Some(query) = line.strip_prefix("> ") else {
                    continue;
                };
                let mut sql = query.to_owned();
                while !sql.trim_end().ends_with(';') {
                    sql.push('\n');
                    sql.push_str(lines.next().context("unterminated example query")?);
                }
                let mut expected = String::new();
                while lines
                    .peek()
                    .is_some_and(|line| line.starts_with(['+', '|']))
                {
                    writeln!(expected, "{}", lines.next().unwrap())?;
                }
                let actual = ctx
                    .sql(&sql)
                    .await
                    .with_context(|| format!("{name}: {sql}"))?
                    .to_string()
                    .await?;
                ensure!(
                    actual.trim() == expected.trim(),
                    "{name}: {sql}\nExpected:\n{expected}\nActual:\n{actual}"
                );
                checked += 1;
            }
            ensure!(checked > 0, "{name}: no example results checked");
        }
        Ok(())
    }
}
